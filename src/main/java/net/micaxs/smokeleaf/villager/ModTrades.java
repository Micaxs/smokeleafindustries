/**
 * Stoner and Dealer trades. Since 26.1 villager trades are data-driven ({@link VillagerTrade} and
 * {@link TradeSet} datapack registries); these are generated by datagen from the bootstrap methods
 * below, and the professions in {@link ModVillagers} point at the per-level trade sets.
 *
 * <p>Each level's trade set offers {@code amount} random, distinct trades out of its pool — the same
 * "pick N of these" behavior the old {@code VillagerTradesEvent} handler had. Where a level used to
 * draw from two separate pools, both pools are now one pool with the picks added together.
 */
