    private static Int2ObjectMap<ResourceKey<TradeSet>> levelKeys(String profession) {
        Int2ObjectMap<ResourceKey<TradeSet>> map = new it.unimi.dsi.fastutil.ints.Int2ObjectOpenHashMap<>();
        for (int level = 1; level <= 5; level++) {
            map.put(level, ResourceKey.create(Registries.TRADE_SET, id(profession + "/level_" + level)));
        }
        return map;
    }

    private static Identifier id(String path) {
        return Identifier.fromNamespaceAndPath(SmokeleafIndustries.MODID, path);
    }

    /** Trade pools per trade set, filled while bootstrapping the trades and read when bootstrapping the sets. */
